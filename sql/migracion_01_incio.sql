BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'CLIENTE',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMIN','CLIENTE'))
);

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL DEFAULT '',
    apellidos VARCHAR(100) NOT NULL DEFAULT '',
    email VARCHAR(254) NOT NULL UNIQUE,
    telefono VARCHAR(20),
    suscrito BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS proveedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    contacto VARCHAR(254),
    material VARCHAR(150),
    notas TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    proveedor_id BIGINT REFERENCES proveedores(id),
    referencia VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    precio NUMERIC(12,2) NOT NULL CHECK (precio > 0),
    precio_anterior NUMERIC(12,2),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    etiqueta VARCHAR(60),
    imagen_url TEXT NOT NULL,
    imagen_alt VARCHAR(254) NOT NULL,
    material VARCHAR(150) NOT NULL DEFAULT 'Acero quirúrgico 316L',
    certificado_url TEXT,
    personalizable BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (precio_anterior IS NULL OR precio_anterior > precio)
);

CREATE TABLE IF NOT EXISTS cupones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descuento INTEGER NOT NULL CHECK (descuento BETWEEN 1 AND 80),
    minimo NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (minimo >= 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    vence_en TIMESTAMPTZ,
    CHECK (codigo = upper(btrim(codigo)) AND codigo ~ '^[A-Z0-9_-]{3,20}$')
);

CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    usuario_id BIGINT REFERENCES usuarios(id),
    clave_solicitud VARCHAR(36) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    tipo_documento VARCHAR(3) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL,
    direccion VARCHAR(254) NOT NULL,
    referencia VARCHAR(254),
    ubigeo_codigo VARCHAR(6) NOT NULL,
    departamento VARCHAR(100) NOT NULL,
    provincia VARCHAR(100) NOT NULL,
    distrito VARCHAR(100) NOT NULL,
    codigo_postal VARCHAR(5),
    cupon_id BIGINT REFERENCES cupones(id),
    codigo_cupon VARCHAR(20),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    descuento NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    costo_envio NUMERIC(12,2) CHECK (costo_envio >= 0),
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    mensaje_regalo VARCHAR(180),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    pagado_en TIMESTAMPTZ,
    correo_enviado_en TIMESTAMPTZ,
    CHECK (tipo_documento IN ('dni','ce','ruc')),
    CHECK (estado IN ('pendiente','pagado','preparando','enviado','entregado','cancelado')),
    CHECK (ubigeo_codigo ~ '^[0-9]{6}$'),
    CHECK (codigo_postal IS NULL OR codigo_postal ~ '^[0-9]{5}$'),
    CHECK (descuento <= subtotal),
    CHECK (total = subtotal - descuento + coalesce(costo_envio,0))
);

CREATE TABLE IF NOT EXISTS detalle_pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    nombre_producto VARCHAR(150) NOT NULL,
    imagen_url TEXT NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0),
    importe NUMERIC(12,2) NOT NULL,
    grabado VARCHAR(20),
    talla VARCHAR(30),
    color VARCHAR(50),
    CHECK (importe = cantidad * precio_unitario)
);

CREATE TABLE IF NOT EXISTS pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedidos(id),
    metodo VARCHAR(20) NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    referencia VARCHAR(100),
    confirmado_en TIMESTAMPTZ,
    CHECK (metodo IN ('yape','plin','transferencia','tarjeta')),
    CHECK (estado IN ('pendiente','confirmado','reembolsado','rechazado'))
);

CREATE TABLE IF NOT EXISTS compras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id BIGINT NOT NULL REFERENCES proveedores(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 1000000),
    costo_unitario NUMERIC(12,2) NOT NULL CHECK (costo_unitario >= 0),
    total NUMERIC(12,2) NOT NULL,
    comprobante VARCHAR(100),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (total = cantidad * costo_unitario)
);

CREATE TABLE IF NOT EXISTS garantias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT REFERENCES pedidos(id),
    nombre_cliente VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    descripcion TEXT NOT NULL,
    evidencia_url TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    nota_admin TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (estado IN ('pendiente','aprobada','rechazada','resuelta')),
    CHECK (length(btrim(descripcion)) >= 10)
);

CREATE TABLE IF NOT EXISTS resenas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    pedido_id BIGINT REFERENCES pedidos(id),
    nombre_cliente VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    contenido TEXT NOT NULL,
    foto_url TEXT,
    verificada BOOLEAN NOT NULL DEFAULT TRUE,
    aprobada BOOLEAN NOT NULL DEFAULT FALSE,
    demostracion BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (producto_id, pedido_id),
    CONSTRAINT resenas_origen_valido CHECK ((demostracion AND pedido_id IS NULL AND NOT verificada) OR (NOT demostracion AND pedido_id IS NOT NULL)),
    CHECK (length(btrim(contenido)) >= 10)
);

CREATE INDEX IF NOT EXISTS idx_productos_categoria ON productos(categoria_id);

CREATE INDEX IF NOT EXISTS idx_pedidos_cliente ON pedidos(cliente_id);

CREATE INDEX IF NOT EXISTS idx_pedidos_usuario ON pedidos(usuario_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_email_normalizado ON usuarios(lower(email));

CREATE INDEX IF NOT EXISTS idx_pedidos_fecha ON pedidos(creado_en);

CREATE INDEX IF NOT EXISTS idx_detalle_pedido ON detalle_pedidos(pedido_id);

CREATE INDEX IF NOT EXISTS idx_detalle_producto ON detalle_pedidos(producto_id);

CREATE INDEX IF NOT EXISTS idx_compras_proveedor ON compras(proveedor_id);

CREATE INDEX IF NOT EXISTS idx_garantias_pedido ON garantias(pedido_id);

CREATE INDEX IF NOT EXISTS idx_resenas_producto ON resenas(producto_id);

